// Open poem modal
function openPoem(id) {
  const poem = poems[id];
  if (!poem) return;

  const modalBody = document.getElementById('modalBody');
  modalBody.innerHTML = `
    <h2>${poem.title}</h2>
    <div class="modal-category">
      <span class="category-tag ${poem.categoryClass}">${poem.category}</span>
    </div>
    <div class="poem-text">${poem.content}</div>
    <div class="poem-author">— ‘चमन’</div>
  `;

  document.getElementById('poemModal').classList.add('active');
  document.body.style.overflow = 'hidden';
}

// Close poem modal
function closePoem() {
  document.getElementById('poemModal').classList.remove('active');
  document.body.style.overflow = '';
}

// Close on outside click
document.getElementById('poemModal').addEventListener('click', function(e) {
  if (e.target === this) closePoem();
});

// Close on Escape key
document.addEventListener('keydown', function(e) {
  if (e.key === 'Escape') closePoem();
});

// Category filter
const filterBtns = document.querySelectorAll('.filter-btn');
const poemCards = document.querySelectorAll('.poem-card');

filterBtns.forEach(btn => {
  btn.addEventListener('click', () => {
    filterBtns.forEach(b => b.classList.remove('active'));
    btn.classList.add('active');

    const filter = btn.getAttribute('data-filter');

    poemCards.forEach(card => {
      if (filter === 'all' || card.getAttribute('data-category') === filter) {
        card.style.display = 'flex';
      } else {
        card.style.display = 'none';
      }
    });
  });
});

// Smooth active nav on scroll
const sections = document.querySelectorAll('section[id]');
window.addEventListener('scroll', () => {
  let current = '';
  sections.forEach(section => {
    const sectionTop = section.offsetTop - 100;
    if (scrollY >= sectionTop) {
      current = section.getAttribute('id');
    }
  });

  document.querySelectorAll('.nav-link').forEach(link => {
    link.classList.remove('active');
    if (link.getAttribute('href') === '#' + current) {
      link.classList.add('active');
    }
  });
});
